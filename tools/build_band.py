#!/usr/bin/env python3
"""Build the homepage band: four questions, four renders, in a row.

This started as a scattered constellation borrowed from a reference Garrett sent -- many
small images with thin SVG lines drawn to each question. It went through nineteen renders
at 38-59px and it did not survive contact: at that size the watermark burned into every
image was unreadable, the absolute positioning stacked into a column on narrow screens, and
the answer when he finally saw it was "I just want 4 images, side by side".

So: a grid. Four cells, each one render over the question it answers, laid out left to
right and reflowing to two columns and then one. No absolute positioning, no SVG, nothing
that can pile up. The renders are ~230px instead of ~50px, which is what makes the
watermark -- model, seed, and the seconds it took on this card -- legible without opening
anything, and clicking still opens the full 768px file.

The four are the ones Garrett picked out of the set. Every one was drawn by the image
surface further down this page. Stock photography on a page arguing that you should own
your AI would lose the argument on the first scroll.

Idempotent: the block lives between markers and is replaced wholesale.
"""
from __future__ import annotations

import json
import pathlib
import re

# The generators live in tools/, so the repo root is one level up. This calculation has
# been wrong four times in this repo and it fails silently.
ROOT = pathlib.Path(__file__).resolve().parent.parent
assert (ROOT / "backend" / "api.py").is_file(), f"repo root not found at {ROOT}"
SITE = ROOT / "site"
INDEX = SITE / "index.html"

BEGIN = "<!-- ===== BAND:BEGIN (generated by tools/build_band.py) ===== -->"
END = "<!-- ===== BAND:END ===== -->"

# (slug, question, alt text, rotation in degrees)
#
# The pairing is not arbitrary. A data centre aisle sits under "what if your data never
# left the building", because that aisle is where it goes today; a hand holding a drive
# sits under the ownership question; a single card on a workbench sits under "do you
# actually need a data centre"; an open chassis on an engineer's desk sits under the one
# about the model knowing your business, because that is the work.
CELLS = [
    ("fast",  "What if your data never<br>left the building?",
     "Long-exposure light trails down a dark data centre aisle", -1.5),
    ("yours", "Who owns your model when<br>the invoice stops?",
     "A hand holding a small labelled hard drive over a dark desk", 1.5),
    ("cost",  "Do you actually need<br>a data centre?",
     "A single graphics card resting on a workbench", -1.5),
    ("build", "Does it actually know how<br>your business works?",
     "An engineer's desk with an open server chassis and a multimeter", 1.5),
]


def cell(slug: str, question: str, alt: str, rot: float) -> str:
    meta = SITE / f"art-{slug}.json"
    prompt = seed = secs = ""
    if meta.is_file():
        d = json.loads(meta.read_text())
        prompt, seed, secs = d.get("prompt", ""), d.get("seed", ""), d.get("seconds", "")
    esc = prompt.replace('"', "&quot;")
    # An <a> to the PNG, not a <figure>. The watermark printed into every render -- model,
    # quantisation, size, steps, seed, seconds -- is the claim this band is making, and it
    # deserves to be readable. ui.js upgrades the link to an overlay; with no JavaScript
    # the link still works and shows the file itself.
    return f"""    <div class="bcell">
      <a class="art" href="/art-{slug}.png" title="{esc}"
         data-prompt="{esc}" data-seed="{seed}" data-secs="{secs}"
         aria-label="Open the full render: {esc}"
         style="--rot:{rot}deg">
        <img src="/art-{slug}.png" alt="{alt}, rendered by SyMoNeuRaL Image"
             loading="lazy" width="768" height="802">
      </a>
      <p class="q">{question}</p>
    </div>"""


def build() -> str:
    cells = "\n".join(cell(*c) for c in CELLS)
    return f"""{BEGIN}
<div class="band">
  <div class="band-mid">
    <h2>Your AI bill is a rent cheque.<br>We build the house.</h2>
    <p class="band-lede">
      Every figure on this site was measured on hardware we own outright &mdash; no vendor
      slides, no estimates, and the results that went against us are published too. We will
      do the same for your business: your server, your models, in your building.
      <b>The invoice stops. The machine does not.</b>
    </p>
    <a class="cta" href="/build.html">Start a build &rarr;</a>
  </div>

  <div class="band-row">
{cells}
  </div>

  <p class="band-foot">
    Every picture here was drawn by <b>SyMoNeuRaL Image</b>, the surface further down this
    page &mdash; same card, same four steps you get. The seed is stamped on each one.
    Nothing here is stock. Click any of them to read it.
  </p>
</div>
{END}"""


def main() -> int:
    html = INDEX.read_text()
    block = build()
    if BEGIN in html and END in html:
        html = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, html, flags=re.S)
        where = "replaced"
    else:
        i = html.index("<!-- ===== RACK:BEGIN")
        html = html[:i] + block + "\n\n" + html[i:]
        where = "inserted"
    INDEX.write_text(html)
    print(f"band {where}: {len(CELLS)} renders, {len(CELLS)} questions, side by side")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
