#!/usr/bin/env python3
"""Build the homepage band: a constellation of small renders wired to four questions.

The band is the page's argument aimed at a business owner — the objections they actually
have — and it borrows its shape from a reference Garrett sent: many *small* images scattered
around each question with thin lines drawn between them, not a few large ones parked in the
corners. The first version used six images at ~150px and read as decoration; this one uses
eighteen at 52-96px and reads as a network.

Two things are load-bearing:

**The lines are SVG, not CSS.** Each is drawn in a 0-100 viewBox with
`preserveAspectRatio="none"` so the constellation stretches with the band, plus
`vector-effect="non-scaling-stroke"` so the stroke stays hairline instead of smearing when
the box is wider than it is tall.

**Every image is a real render from this machine**, watermarked with its model, seed and the
seconds it took. `tools/build_gallery.py` makes them. Stock photography on a page arguing
that you should own your AI would lose the argument on the first scroll.

Idempotent: the block lives between markers and is replaced wholesale.
"""
from __future__ import annotations

import json
import pathlib

# The generators live in tools/, so the repo root is one level up. This calculation has
# been wrong four times in this repo and it fails silently.
ROOT = pathlib.Path(__file__).resolve().parent.parent
assert (ROOT / "backend" / "api.py").is_file(), f"repo root not found at {ROOT}"
SITE = ROOT / "site"
INDEX = SITE / "index.html"

BEGIN = "<!-- ===== BAND:BEGIN (generated by tools/build_band.py) ===== -->"
END = "<!-- ===== BAND:END ===== -->"

# Four clusters. Each is a question anchored at (x, y) in percent, with the renders that
# hang off it. Sizes vary deliberately: a uniform grid reads as a contact sheet, uneven
# sizes read as a constellation.
#   (slug, x%, y%, width px, rotation deg)
CLUSTERS = [
    {
        "q": "What if your data never<br>left the building?",
        "qx": 15.5, "qy": 33, "align": "left",
        "art": [
            ("owns", 6.0, 11.0, 59, -5),
            ("vault", 15.5, 15.0, 43, 4),
            ("chip", 22.5, 24.0, 41, -3),
            ("private", 3.5, 27.0, 50, 6),
            ("map", 11.0, 45.0, 46, -4),
            ("cable", 21.0, 48.0, 38, 5),
        ],
    },
    {
        "q": "Who owns your model when<br>the invoice stops?",
        "qx": 17.5, "qy": 71, "align": "left",
        "art": [
            ("yours", 5.0, 60.0, 55, 5),
            ("box", 13.5, 63.0, 39, -6),
            ("token", 24.0, 65.0, 38, 3),
            ("hands", 8.0, 83.0, 49, -4),
            ("clock", 19.5, 86.0, 41, 6),
        ],
    },
    {
        "q": "Do you actually need<br>a data centre?",
        "qx": 81, "qy": 30, "align": "right",
        "art": [
            ("cost", 72.0, 11.0, 56, 5),
            ("rack2", 84.5, 13.0, 42, -4),
            ("gpu", 92.5, 21.0, 46, 3),
            ("desk", 75.5, 25.0, 38, -6),
            ("meter", 88.0, 37.0, 50, 4),
        ],
    },
    {
        "q": "What would you ask an AI<br>that nobody else can see?",
        "qx": 80, "qy": 73, "align": "right",
        "art": [
            ("fast", 73.0, 60.0, 52, -5),
            ("build", 85.5, 62.0, 41, 4),
            ("token2", 93.0, 70.0, 38, -3),
        ],
    },
]

ALT = {
    "owns": "A server rack glowing in a dark office", "cost": "A graphics card on a workbench",
    "private": "A locked door inside a server room", "fast": "Light trails down a data centre aisle",
    "yours": "A hand holding a labelled drive", "build": "An engineer's desk with an open chassis",
    "gpu": "A graphics card fan blade", "rack2": "Three stacked server units",
    "cable": "Coiled network cables", "chip": "A silicon die under magnification",
    "desk": "A laptop beside a small server tower", "meter": "An analogue power meter",
    "vault": "A heavy safe door ajar", "map": "A network graph of glowing nodes",
    "box": "A shipping box under one light", "token": "Streams of glowing particles",
    "hands": "A handshake in front of a server rack", "clock": "A clock in a dark server room",
}


def build() -> str:
    arts, lines, qs = [], [], []
    for i, c in enumerate(CLUSTERS):
        qs.append(
            f'  <p class="q q{i}" style="left:{c["qx"]}%;top:{c["qy"]}%;text-align:{c["align"]}">'
            f'{c["q"]}</p>'
        )
        for slug, x, y, w, rot in c["art"]:
            src = slug if (SITE / f"art-{slug}.png").is_file() else slug.rstrip("2")
            # The prompt is the provenance, and at 52-96px it cannot be printed under the
            # image without becoming noise -- so it appears on hover, and in title= for
            # anyone using a pointer or a screen reader. Everything here was typed into the
            # image surface below; showing the exact words is the point.
            meta = SITE / f"art-{src}.json"
            prompt = seed = secs = ""
            if meta.is_file():
                d = json.loads(meta.read_text())
                prompt, seed, secs = d.get("prompt", ""), d.get("seed", ""), d.get("seconds", "")
            esc = prompt.replace('"', "&quot;")
            cap = (f'<figcaption><q>{prompt}</q>'
                   f'<span>FLUX.1-schnell &middot; 4 steps &middot; seed {seed} &middot; {secs}s '
                   f'on an RTX&nbsp;5070&nbsp;Ti</span></figcaption>') if prompt else ""
            arts.append(
                f'    <figure class="art" style="left:{x}%;top:{y}%;width:{w}px;'
                f'transform:rotate({rot}deg)" title="{esc}">'
                f'<img src="/art-{src}.png" alt="{ALT.get(slug, "Rendered by SyMoNeuRaL Image")}, '
                f'rendered by SyMoNeuRaL Image" loading="lazy" width="768" height="802">'
                f'{cap}</figure>'
            )
            # from the question anchor to the centre of the render
            lines.append(f'    <line x1="{c["qx"]}" y1="{c["qy"]}" x2="{x}" y2="{y}" />')

    return f"""{BEGIN}
<div class="band">
  <svg class="band-lines" viewBox="0 0 100 100" preserveAspectRatio="none" aria-hidden="true">
{chr(10).join(lines)}
  </svg>

  <div class="band-art">
{chr(10).join(arts)}
  </div>

{chr(10).join(qs)}

  <div class="band-mid">
    <h2>SyMoNeuRaL is built on one<br>deeply boring question.</h2>
    <p class="band-lede">
      <b>Why are you renting this?</b> Every number on this site was measured on hardware
      we own outright. We will do the same for your business, on a server you own outright,
      running models that answer to you.
    </p>
    <a class="cta" href="#order">Start a build &rarr;</a>
    <p class="band-foot">
      Every picture here was drawn by the image surface below &mdash; same card, same four
      steps you get, seed stamped on each one. Nothing is stock.
    </p>
  </div>
</div>
{END}"""


def main() -> int:
    html = INDEX.read_text()
    block = build()
    if BEGIN in html and END in html:
        import re
        html = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, html, flags=re.S)
        where = "replaced"
    else:
        anchor = "<!-- ===== RACK:BEGIN"
        i = html.index(anchor)
        # the hand-written band that preceded this generator
        j = html.rfind("<!-- ===================== BAND ===================== -->", 0, i)
        if j != -1:
            html = html[:j] + block + "\n\n" + html[i:]
        else:
            html = html[:i] + block + "\n\n" + html[i:]
        where = "inserted"
    INDEX.write_text(html)
    n = sum(len(c["art"]) for c in CLUSTERS)
    print(f"band {where}: {n} renders, {len(CLUSTERS)} questions, {n} connecting lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
