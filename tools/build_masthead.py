#!/usr/bin/env python3
"""Build the top of the front page: the pitch and the hero, side by side, with a render
in each gutter.

These were two stacked full-width sections. The hero introduced the company, then a
930px-tall band restated the argument, and the rack -- the entire point of the page, the
machine reading its own sensors while you watch -- began somewhere around 1,300px down.
Garrett's requirement, and it is the right one: pitch, hero and rack all visible on a
first look at 100% zoom.

So they sit beside each other. The hero is on the right where the eye lands after the nav,
the pitch on the left, and the two renders that used to eat a full screen in a four-across
row now occupy the gutters either side -- space that was empty at any width above 1280px.
Two more sit either side of the rack immediately below, which is the same trade: the rack
is 1120px wide inside a 1900px viewport and the gutters were doing nothing.

`h1` comes first in the document and is placed on the right by grid area, rather than
writing an `h2` above the page's `h1` to get the visual order.

Idempotent: the block lives between markers and is replaced wholesale. It replaces both
the old hand-written hero and the generated BAND block, which is why it looks for either.
"""
from __future__ import annotations

import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import _art  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
assert (ROOT / "backend" / "api.py").is_file(), f"repo root not found at {ROOT}"
INDEX = ROOT / "site" / "index.html"

BEGIN = "<!-- ===== MASTHEAD:BEGIN (generated by tools/build_masthead.py) ===== -->"
END = "<!-- ===== MASTHEAD:END ===== -->"

# The two questions that pair with the top of the page: where the data goes, and who owns
# the thing afterwards. The hardware and fine-tune questions sit beside the rack, next to
# the hardware they are about.
LEFT = _art.gutter(
    "fast", "Long-exposure light trails down a dark data centre aisle",
    "What if your data never<br>left the building?", -1.5)
RIGHT = _art.gutter(
    "yours", "A hand holding a small labelled hard drive over a dark desk",
    "Who owns your model when<br>the invoice stops?", 1.5)

BLOCK = f"""{BEGIN}
<!-- id="hero" is the handle tools/build_tabs.py needs to treat the masthead as the first
     panel of the one-screen layout. Without it the tab strip has nothing to hide, the
     masthead stays stacked above the panels and squeezes them to a slit. Keep them in
     step: build_tabs.py asserts this id is here rather than silently producing that slit. -->
<div class="masthead" id="hero">
  <div class="mh">
    <div class="mh-hero">
      <p class="eyebrow">SyMoNeuRaL Local Infrastructure</p>
      <h1>Custom AI platforms that live in <i>your</i> building.</h1>
      <p class="mh-body">
        SyMoNeuRaL builds custom AI stacks for any business, on any hardware, specialising
        in NVIDIA servers. You are looking at one right now: this entire site &mdash; chat,
        image, algebra, the fine-tune &mdash; runs on a single consumer graphics card in
        our workshop.
      </p>
      <p class="tiny">
        If a $1,000 card can do this, imagine what a real server does for your business.
      </p>
      <div class="actions">
        <a class="cta" href="/build.html">Have one built &rarr;</a>
        <a class="cta ghost" href="#rack">See it running</a>
      </div>
    </div>

    <div class="mh-pitch">
      <h2>Your AI bill is a rent cheque.<br>We build the house.</h2>
      <p class="mh-lede">
        Every figure on this site was measured on hardware we own outright &mdash; no
        vendor slides, no estimates, and the results that went against us are published
        too. <b>The invoice stops. The machine does not.</b>
      </p>
      <a class="cta ghost" href="/build.html">Start a build &rarr;</a>
      <p class="mh-foot">
        All four pictures on this page were drawn by <b>SyMoNeuRaL Image</b>, the surface
        on the rack below &mdash; same card, same four steps you get. Nothing is stock.
      </p>
    </div>

    {LEFT}
    {RIGHT}
  </div>
</div>
{END}"""

# The two blocks this replaces, in the order they appeared.
OLD_HERO = re.compile(r'<!-- =+ HERO =+ -->\n<div class="hero split">.*?\n</div>\n\n', re.S)
OLD_BAND = re.compile(r'<!-- ===== BAND:BEGIN.*?<!-- ===== BAND:END ===== -->\n', re.S)


def main() -> int:
    html = INDEX.read_text()
    if BEGIN in html and END in html:
        html = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: BLOCK, html, flags=re.S)
        where = "replaced"
    else:
        html, band = OLD_BAND.subn("", html)
        html, hero = OLD_HERO.subn(lambda _: BLOCK + "\n\n", html)
        if not hero:
            raise SystemExit("no hero block and no masthead markers -- nothing to anchor to")
        where = f"inserted (dropped {band} old band block, {hero} old hero block)"
    INDEX.write_text(html)
    print(f"masthead {where}: hero + pitch side by side, 2 gutter renders")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
