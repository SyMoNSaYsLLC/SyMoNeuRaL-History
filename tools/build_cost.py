#!/usr/bin/env python3
"""Inject the side-by-side cost comparison: this card against rented 48 GB class.

The point of this section is a single honest comparison, and it has to carry both halves or
it is an advertisement. The card wins on cost by a wide margin and loses on capacity by a
wide margin, and a reader deciding what to buy needs both numbers on the same screen.

Every cloud rate here comes from a real listing, is labelled as an observed rate rather than
a quote, and is dated -- these move monthly and a stale number presented as current is the
same failure as an unmeasured benchmark presented as measured.

Idempotent: lives between markers, replaced wholesale.
"""
from __future__ import annotations

import pathlib
import re

# The generators live in tools/, so the repo root is one level up. This exact
# calculation has been wrong twice in this repo's history -- once when demo/ was
# flattened and once here -- and it fails *silently*, because the wrong parent is
# usually a directory that exists. Assert rather than trust it.
ROOT = pathlib.Path(__file__).resolve().parent.parent
assert (ROOT / "backend" / "api.py").is_file(), f"repo root not found at {ROOT}"
SITE = ROOT / "site"
INDEX = SITE / "documentation.html"

BEGIN = "<!-- ===== COST:BEGIN (generated by build_cost.py) ===== -->"
END = "<!-- ===== COST:END ===== -->"

CARD_COST = 1000
POWER_W = 300
KWH = 0.15
RUN_HR = POWER_W / 1000 * KWH          # $0.045/hr at full tilt

# (provider, vram, gpus, host, $/hr) -- observed listings, August 2026
CLOUD = [
    ("MassedCompute", "48 GB", 1, "72 GB RAM &times; 12 vCPU", 1.06),
    ("Crusoe", "48 GB", 1, "147 GB RAM &times; 8 vCPU", 1.74),
    ("DMZ", "48 GB", 1, "500 GB RAM &times; 128 vCPU", 1.90),
    ("Scaleway", "48 GB", 1, "96 GB RAM &times; 8 vCPU", 2.04),
    ("AWS", "44.70 GiB", 1, "32 GiB RAM &times; 4 vCPU", 2.23),
    ("Crusoe", "48 GB &times; 2", 2, "294 GB RAM &times; 16 vCPU", 3.48),
]


def rows() -> str:
    out = [
        '<tr style="background:rgba(46,224,138,.06)">'
        '<td class="k"><b>This machine &mdash; RTX 5070 Ti</b></td>'
        '<td class="num"><b>15.92 GiB</b></td>'
        '<td>owned outright</td>'
        f'<td class="num"><b>${RUN_HR:.3f}/hr</b></td>'
        f'<td class="num"><b>${CARD_COST + RUN_HR * 8760:,.0f}</b></td>'
        '<td>&mdash;</td></tr>'
    ]
    for provider, vram, _gpus, host, rate in CLOUD:
        break_even = CARD_COST / (rate - RUN_HR) / 24
        out.append(
            f'<tr><td class="k">{provider}</td>'
            f'<td class="num">{vram}</td>'
            f'<td>{host}</td>'
            f'<td class="num">${rate:.2f}/hr</td>'
            f'<td class="num"><em>${rate * 8760:,.0f}</em></td>'
            f'<td class="num">{break_even:.0f} days</td></tr>')
    return "\n          ".join(out)


COST = f"""{BEGIN}
<section id="cost">
  <div class="wrap">
    <p class="shead"><img src="/coin-64.png" alt="" width="22" height="22">Owned vs Rented</p>
    <h2>A $1,000 card beside a rented 48&nbsp;GB server</h2>
    <p class="sub">
      The card this whole site was measured on, against real listings for the 48&nbsp;GB
      class. Both halves of the answer are here: what it costs, and what it cannot do.
    </p>

    <div class="grid g2" style="margin-top:28px">
      <div class="card" style="border-color:rgba(46,224,138,.4)">
        <img class="ico" src="/mark-64.png" alt="" width="38" height="38">
        <h3>RTX 5070 Ti &mdash; this machine</h3>
        <p><code>15.92 GiB</code> &middot; 8,960 CUDA cores &middot; <b>752 GB/s measured</b><br>
           PCIe Gen&nbsp;3 &times;8 host cap &middot; 300 W &middot; sm_120</p>
        <p><b>~$1,000 once</b>, then ${RUN_HR:.3f}/hr of electricity at full tilt.
           A year of running it flat out, all in, is
           <b>${CARD_COST + RUN_HR * 8760:,.0f}</b>.</p>
        <p>Ceiling: a 14B at Q4, or a 32B at IQ2 with little context headroom.</p>
      </div>
      <div class="card" style="border-color:rgba(255,171,61,.35)">
        <img class="ico" src="/studio-64.png" alt="" width="38" height="38">
        <h3>Rented 48&nbsp;GB class</h3>
        <p><code>48 GB</code> &middot; three times the memory &middot; enterprise interconnect,
           ECC, and somebody else's problem when it breaks.</p>
        <p><b>$1.06&ndash;$3.48/hr</b> observed. Run continuously that is
           <em>$9,286&ndash;$30,485 a year</em>, and you own nothing at the end of it.</p>
        <p>Ceiling: a 70B at Q4 comfortably &mdash; which the card on the left
           <strong>cannot run at any price</strong>.</p>
      </div>
    </div>

    <div class="tw">
      <table>
        <caption>Observed 48&nbsp;GB-class rates, August 2026 &mdash; against this machine</caption>
        <thead><tr>
          <th>Provider</th><th>VRAM</th><th>Host</th><th>Rate</th>
          <th>1 year, 24/7</th><th>Break-even vs the card</th>
        </tr></thead>
        <tbody>
          {rows()}
        </tbody>
      </table>
    </div>
    <p class="tnote">
      Break-even is the card's purchase price divided by the hourly rate net of its own
      electricity &mdash; <b>12 to 41 days</b> depending on the provider. After that the
      owned card is free and the rented one is not.
      <strong>The honest other half:</strong> three times the VRAM is not a luxury, it is the
      difference between running a 70B and not running it. Cheap per gigabyte is not the same
      as enough gigabytes, and which one you are short of is the entire consultation.
      Rates are observed public listings, not quotes, and they move monthly; electricity at
      $0.15/kWh. We will not quote a number we have not either measured or shown the
      arithmetic for.
    </p>
  </div>
</section>
{END}"""


def main() -> int:
    html = INDEX.read_text()
    if BEGIN in html and END in html:
        html = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), COST, html, flags=re.S)
        where = "replaced"
    else:
        anchor = '<!-- ===== STACK:BEGIN'
        if anchor not in html:
            print("stack marker not found -- run build_stack.py first")
            return 1
        html = html.replace(anchor, COST + "\n\n" + anchor, 1)
        where = "inserted"
    INDEX.write_text(html)
    print(f"cost section {where} ({len(COST):,} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
