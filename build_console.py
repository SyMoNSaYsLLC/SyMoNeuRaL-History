def wrap_folds(html: str) -> tuple[str, int]:
    """Wrap each long section in a <details> without touching its contents.

    Idempotent by checking for the fold this run would create. Without that guard a second
    run nests each section inside a second <details> -- the page still renders, which is
    what makes it nasty: you get a fold inside a fold and have to click twice to reach a
    table that was one click away before.
    """
    count = 0
    for sid, (label, spec) in FOLDS.items():
        if f'id="fold-{sid}"' in html:
            continue
        pattern = re.compile(
            r'(<section id="' + sid + r'">\s*<div class="wrap">)(.*?)(</div>\s*</section>)',
            re.S)
        match = pattern.search(html)
        if not match:
            continue
        head, inner, tail = match.groups()
        # Drop the section's own eyebrow/h2/sub -- the summary row now carries that role,
        # and repeating it inside the fold is the kind of duplication that makes a
        # collapsed page feel longer than the one it replaced.
        inner = re.sub(r'<p class="shead">.*?</p>\s*', "", inner, count=1, flags=re.S)
        inner = re.sub(r"<h2>.*?</h2>\s*", "", inner, count=1, flags=re.S)
        icon = ICONS.get(sid, "/mark-32.png")
        folded = (
            f'{head}\n    <details class="fold" id="fold-{sid}">\n'
            f'      <summary><img src="{icon}" alt="">{label}<span>{spec}</span></summary>\n'
            f'      <div class="foldbody">{inner}</div>\n'
            f'    </details>\n  {tail}'
        )
        html = html[:match.start()] + folded + html[match.end():]
        count += 1
    return html, count


def main() -> int:
    html = INDEX.read_text()

    if BEGIN in html and END in html:
        html = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), CONSOLE, html, flags=re.S)
        placed = "replaced"
    else:
        anchor = "<!-- ===== RACK:BEGIN"
        if anchor not in html:
            print("rack marker not found -- run build_rack.py first")
            return 1
        html = html.replace(anchor, CONSOLE + "\n\n" + anchor, 1)
        placed = "inserted"

    html, folded = wrap_folds(html)

    # Trim the hero: the console is the headline now, so the hero only has to say who we
    # are and get out of the way.
    html = re.sub(r'<div class="hero">', '<div class="hero" style="padding:52px 0 8px">',
                  html, count=1)

    INDEX.write_text(html)
    print(f"console {placed}; {folded} sections folded")
    print(f"index.html: {len(html):,} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
