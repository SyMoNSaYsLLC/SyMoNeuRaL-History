#!/usr/bin/env bash
# Create a bitbake build directory wired to every meta-symoneural-* layer.
#
#     yocto/scripts/setup-build.sh [BUILDDIR]        # default /home/google/yocto/build-symoneural
#
# Then, in a shell where the environment has been sourced:
#
#     bitbake -p                                     # parse only -- the cheap check
#     bitbake symoneural-image
#     bitbake symoneural-image -c populate_sdk
#
# This script does NOT source the environment for you. `oe-init-build-env` must be sourced
# into your interactive shell to have any effect, and a child process sourcing it and
# exiting changes nothing -- which is a confusing way to fail, so it prints the line
# instead of pretending.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
[ -f "$REPO/backend/api.py" ] || { echo "repo root not found at $REPO" >&2; exit 1; }
LAYERS="$REPO/yocto"
POKY="${POKY:-/home/google/yocto}"
BUILD="${1:-$POKY/build-symoneural}"

for req in "$POKY/openembedded-core/oe-init-build-env" "$POKY/bitbake/bin/bitbake"; do
  [ -e "$req" ] || { echo "missing: $req" >&2
                     echo "openembedded-core and bitbake must be under $POKY" >&2; exit 1; }
done

mkdir -p "$BUILD/conf"

# --- bblayers.conf -----------------------------------------------------------
# Written every time, not merged. A bblayers.conf that accumulates entries across runs is
# how a layer that was deleted from disk stays in the list and breaks every parse with
# "Layer directory does not exist".
{
  echo '# Generated by yocto/scripts/setup-build.sh -- edit that script, not this file.'
  echo 'POKY_BBLAYERS_CONF_VERSION = "2"'
  echo 'BBPATH = "${TOPDIR}"'
  echo 'BBFILES ?= ""'
  echo 'BBLAYERS ?= " \'
  echo "  $POKY/openembedded-core/meta \\"
  # meta-oe is listed conditionally. On this box its LAYERSERIES_COMPAT does not include
  # the core's series, and bitbake treats that as fatal -- so including it unconditionally
  # would make every parse fail with a message about compatibility that reads like our
  # layers are broken. The Apple bridge recipes live in it, so when it is skipped, say so.
  core_series="$(sed -n 's/^LAYERSERIES_COMPAT_core *= *"\(.*\)"/\1/p' \
      "$POKY/openembedded-core/meta/conf/layer.conf" 2>/dev/null)"
  oe_series="$(sed -n 's/^LAYERSERIES_COMPAT_openembedded-layer *= *"\(.*\)"/\1/p' \
      "$POKY/meta-openembedded/meta-oe/conf/layer.conf" 2>/dev/null)"
  SKIP_OE=1
  case " $oe_series " in *" $core_series "*) SKIP_OE=0;; esac
  if [ -d "$POKY/meta-openembedded/meta-oe" ] && [ "$SKIP_OE" -eq 0 ]; then
    for l in meta-oe meta-python meta-networking meta-filesystems meta-initramfs; do
      echo "  $POKY/meta-openembedded/$l \\"
    done
  fi
  for l in "$LAYERS"/meta-symoneural-*; do
    name="$(basename "$l")"
    # mingw and aws depend on upstream layers that are not on this box. Listing them
    # anyway gives "Layer depends on ... which is not enabled", a fatal error, so they are
    # included only when their dependency is present.
    case "$name" in
      meta-symoneural-mingw) [ -d "$POKY/meta-mingw" ] || continue;;
      meta-symoneural-aws)   [ -d "$POKY/meta-aws" ]   || continue;;
    esac
    echo "  $l \\"
  done
  [ -d "$POKY/meta-mingw" ] && echo "  $POKY/meta-mingw \\"
  [ -d "$POKY/meta-aws" ]   && echo "  $POKY/meta-aws \\"
  echo '  "'
} > "$BUILD/conf/bblayers.conf"

# --- local.conf --------------------------------------------------------------
if [ -f "$BUILD/conf/local.conf" ]; then
  echo "keeping existing $BUILD/conf/local.conf"
else
  cat > "$BUILD/conf/local.conf" <<LOCALCONF
# Generated once by yocto/scripts/setup-build.sh. Yours to edit from here.
MACHINE ?= "symoneural-workstation"
DISTRO ?= "symoneural"

# Where the recipes read this project's source from. There is no git remote by design, so
# the fetcher uses the file protocol against the checkout.
SYMONEURAL_GIT = "$REPO"

# Pin this to a SHA for anything you intend to reproduce. Left at AUTOREV a rebuild
# silently tracks the working branch, so two builds labelled 0.1.0 need not be the same.
# The placeholder is deliberately not a revision. This line previously read "df1d862", a
# real but arbitrary docs commit, and a SHA written into a comment is wrong from the next
# commit onward -- whoever copies it pins a reproducible build to an unrelated point in
# history and gets exactly the false confidence the pin was supposed to prevent.
# SYMONEURAL_SRCREV = "<output of git -C $REPO rev-parse HEAD>"

DL_DIR ?= "$POKY/downloads"
SSTATE_DIR ?= "$POKY/sstate-cache"
# 20 cores on the reference box, minus headroom so an interactive session stays usable
# while a build runs -- and the GPU surfaces keep answering.
BB_NUMBER_THREADS ?= "16"
PARALLEL_MAKE ?= "-j 16"

# rm_work reclaims the per-recipe work directories as each recipe finishes. Without it a
# full image build of this size leaves tens of gigabytes of intermediate trees behind, on
# the same disk that holds the 104 GiB of weights.
INHERIT += "rm_work"

CONF_VERSION = "2"
LOCALCONF
fi

echo "build dir   $BUILD"
echo "layers      $(grep -c 'meta' "$BUILD/conf/bblayers.conf") entries"
sed -n '/BBLAYERS/,/"$/p' "$BUILD/conf/bblayers.conf" | sed 's/^/  /'
echo
if [ "${SKIP_OE:-1}" -eq 1 ]; then
  cat <<OENOTE
NOTE: meta-openembedded was NOT added.
  openembedded-core reports LAYERSERIES_COMPAT_core = "${core_series:-?}"
  meta-oe accepts                                    "${oe_series:-?}"
bitbake treats that mismatch as fatal, so adding it would break every parse. The Apple
device bridge (usbmuxd, libimobiledevice) and the python3-fastapi recipes live in
meta-openembedded, so until it is updated those recipes are unavailable:

  git -C $POKY/meta-openembedded fetch --all
  git -C $POKY/meta-openembedded checkout <branch naming ${core_series:-the core series}>

OENOTE
fi
cat <<NEXT
Source the environment into YOUR shell -- not this script's:

  cd $POKY && source openembedded-core/oe-init-build-env $BUILD
  bitbake -p                      # parse everything; the cheapest real check
  bitbake symoneural-image
NEXT
